let diaSemana = 7;
switch (diaSemana) {
    case 1:
        console.log("Segunda-feira");
        break;
    case 2:
        console.log("terça-feira");
        break;
    case 3:
        console.log("quarta-feira");
        break;
    case 4:
        console.log("quinta-feira");
        break;
    case 5:
        console.log("sexta-feira");
        break;
    case 6:
        console.log("Sábado");
        break;
    
    case 7:
        console.log("domingo");
        break;

    default:
        console.log("informe um número de 1 a 7");
        
        break;
}